import type { Campaign, Contribution, UserProfile, CampaignCategory } from '../types/campaign';

const DAY = 24 * 60 * 60 * 1000;
const NOW = Date.now();
const iso = (t: number) => new Date(t).toISOString();

function makeCampaign(overrides: Partial<Campaign> & { id: string; title: string; funding_goal: number }): Campaign {
  const fundingCurrent = overrides.funding_current || 0;
  const base: Campaign = {
    slug: overrides.slug || overrides.id,
    tagline: '',
    short_description: '',
    long_description: '',
    why_backers_should_care: '',
    category: 'public_policy',
    status: 'Approved',
    currency: 'usd',
    funding_current: 0,
    amount_raised: 0,
    percent_funded: 0,
    thumbnail_url: '',
    ad_image_url: '',
    ad_headline: '',
    ad_primary_text: '',
    ad_image_prompt: '',
    target_audience: '',
    creator_name: 'Demo Creator',
    created_by: null,
    created_at: iso(NOW - 20 * DAY),
    campaign_starts_at: iso(NOW - 12 * DAY),
    launched_at: iso(NOW - 12 * DAY),
    duration_days: 30,
    evergreen: false,
    show_countdown: true,
    campaign_sources: [],
    ad_platforms: ['facebook', 'instagram'],
    milestones: [],
    hero_slideshow: [],
    stripe_product_id: 'prod_demo_' + overrides.id,
    slides: [],
    ...overrides,
  };
  base.funding_current = fundingCurrent;
  base.amount_raised = fundingCurrent;
  base.percent_funded = overrides.funding_goal ? Math.round((fundingCurrent / overrides.funding_goal) * 100) : 0;
  return base;
}

